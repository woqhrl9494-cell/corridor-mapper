import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url)), inputs = new Map();
function read(path) {
  const key = relative(root, resolve(root, path)).replaceAll('\\', '/');
  if (!inputs.has(key)) inputs.set(key, readFileSync(resolve(root, key), 'utf8'));
  return inputs.get(key);
}
read('build-drf-offline.mjs');
const workerConstructor = "new Worker(new URL('./sweep.worker.mjs?v=20261002-fleet11', import.meta.url), { type: 'module' })";
const options = {
  absWorkingDir: root, bundle: true, platform: 'browser', format: 'iife', target: 'es2022',
  write: false, minify: true, define: { 'import.meta.url': 'globalThis.__drfOffline.moduleUrl' },
  plugins: [{ name: 'offline-workers', setup(builder) {
    builder.onLoad({ filter: /\.(mjs|js)$/ }, ({ path }) => {
      let contents = read(path);
      if (path.endsWith('/drf/sweep.mjs')) {
        if (contents.split(workerConstructor).length !== 2) throw new Error('Sweep worker constructor changed; update offline build.');
        // Only the generated file changes transport; the validated sweep source stays intact.
        contents = contents.replace(workerConstructor, "globalThis.__drfOffline.worker('sweep')");
      }
      return { contents, loader: 'js' };
    });
  } }],
};
const names = ['scenario', 'field', 'eval', 'sweep'];
const bundles = await Promise.all([...names.map(name => `drf/${name}.worker.mjs`), 'drf/app.mjs']
  .map(entry => build({ ...options, entryPoints: [entry] })));
const sources = Object.fromEntries(names.map((name, i) => [name, bundles[i].outputFiles[0].text]));
const metadata = ['drf/provenance.json', 'drf/reference/octave/fixtures.json'].map(path => JSON.parse(read(path)));
const sourceHashes = Object.fromEntries([...inputs].sort(([a], [b]) => a.localeCompare(b))
  .map(([path, source]) => [path, createHash('sha256').update(source).digest('hex')]));
const bootstrap = `// Generated by npm run build:drf-offline; do not edit.\n(() => {
  const sources = ${JSON.stringify(sources)}, urls = new Map();
  globalThis.__drfOffline = {
    metadata: ${JSON.stringify(metadata)}, sourceHashes: ${JSON.stringify(sourceHashes)},
    moduleUrl: new URL('drf/app.mjs', document.baseURI).href,
    worker(name) {
      if (!Object.hasOwn(sources, name)) throw new Error('Unknown DRF worker: ' + name);
      if (!urls.has(name)) urls.set(name, URL.createObjectURL(new Blob([sources[name]], { type: 'text/javascript' })));
      return new Worker(urls.get(name));
    }
  };
  window.addEventListener('beforeunload', () => { for (const url of urls.values()) URL.revokeObjectURL(url); });
})();\n// Bundled app follows.\n`;
writeFileSync(resolve(root, 'drf/offline.bundle.js'), bootstrap + bundles.at(-1).outputFiles[0].text);
console.log(`Built drf/offline.bundle.js from ${inputs.size} source files.`);
